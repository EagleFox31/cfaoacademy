const codes = new Map()
for (const s of raw) {
  const c = canonicalTrainingCode(s.code)
  if (!c || c === '—') continue
  if (!codes.has(c)) codes.set(c, EN[c] ?? '')
}

const missing = [...codes.keys()].filter((k) => !EN[k])
if (missing.length) {
  console.warn('Missing EN translations:', missing.join(', '))
}

const en = Object.fromEntries(
  [...codes.entries()].filter(([, v]) => v).sort(([a], [b]) => a.localeCompare(b)),
)

